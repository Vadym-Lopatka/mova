//! Tricky kondo-parity cases found while diffing against the JVM oracle.
use nx_core::analyzer::*;
use nx_core::intern;

fn run(src: &str, kind: FileKind) -> FileAnalysis {
    let cfg = Config::new();
    let mut defs = DefsIndex::new();
    let mut fa = analyze_file(src, kind, &cfg, &defs);
    defs.add_file(&fa);
    finish_usages(&mut fa, &defs);
    fa
}
fn clj(src: &str) -> FileAnalysis {
    run(src, FileKind::Clj)
}
fn usages<'a>(fa: &'a FileAnalysis, name: &str) -> Vec<&'a VarUsage> {
    fa.var_usages.iter().filter(|u| u.name.as_str() == name).collect()
}

#[test]
fn hof_registers_two_usages_second_without_name_position() {
    let fa = clj("(ns a)\n(defn f [xs] (map inc xs))");
    let u = usages(&fa, "inc");
    assert_eq!(u.len(), 2);
    let plain = u.iter().find(|x| x.arity == NO_ARITY).unwrap();
    let hof = u.iter().find(|x| x.arity == 1).unwrap();
    assert!(plain.name_pos.row != 0);
    assert_eq!(hof.name_pos.row, 0, "hof-call name has no metadata in kondo");
    assert_eq!(hof.pos, plain.pos);
    assert_eq!(hof.to, intern("clojure.core"));
}

#[test]
fn syntax_quote_gensym_is_unresolved_usage() {
    let fa = clj("(ns a)\n(defmacro m [x] `(let [y# ~x] y#))");
    let u = usages(&fa, "y#");
    assert_eq!(u.len(), 2);
    assert!(u.iter().all(|x| x.to == intern("clj-kondo/unknown-namespace")));
}

#[test]
fn threading_uses_form_positions_and_generated_calls_have_none() {
    let fa = clj("(ns a)\n(defn f [x] (-> x (assoc :a 1)) (cond-> x true inc))");
    let assoc = usages(&fa, "assoc")[0];
    assert_eq!(assoc.arity, 3); // threaded arg counts
    assert_eq!((assoc.pos.row, assoc.pos.col), (2, 19)); // position of `(assoc :a 1)`
    // `let`/`if` generated by cond-> carry no position at all
    let l = usages(&fa, "let");
    assert!(l.iter().any(|u| u.pos.row == 0 && u.name_pos.row == 0));
}

#[test]
fn fn_literal_params_and_percent() {
    let fa = clj("(ns a)\n(defn f [xs] (map #(inc %) xs))");
    let f = usages(&fa, "fn*");
    assert_eq!(f.len(), 1);
    assert!(f[0].pos.row != 0 && f[0].name_pos.row == 0);
    // `%` is a pseudo binding: a usage without id and name; `%1` params register no local
    assert!(fa.local_usages.iter().any(|u| u.id == 0 && u.name.is_none()));
    assert!(fa.locals.iter().all(|l| l.name.as_str() != "%1"));
}

#[test]
fn type_hint_is_a_nameless_local_usage() {
    let fa = clj("(ns a)\n(defn f [^long x] x)");
    let hint: Vec<_> = fa.local_usages.iter().filter(|u| u.id == 0).collect();
    assert_eq!(hint.len(), 1);
    assert!(hint[0].name.is_none());
}

#[test]
fn deftest_is_defn_with_test_flag_and_callstack() {
    let fa = clj("(ns a (:require [clojure.test :refer [deftest is]]))\n(deftest t (is (= 1 1)))");
    let d = fa.var_definitions.iter().find(|d| d.name.as_str() == "t").unwrap();
    assert!(d.test);
    assert_eq!(d.defined_by, (intern("clojure.test"), intern("deftest")));
    assert_eq!(fa.callstacks[d.cs.0 as usize], (intern("clojure.test"), intern("deftest")));
    let refer = fa.var_usages.iter().filter(|u| u.refer).count();
    assert_eq!(refer, 2);
}

