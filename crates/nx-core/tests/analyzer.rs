#[test]
fn unloaded_namespace_has_no_target_info_when_only_used_in_try_body() {
    // kondo drops results of a `try` body, so a namespace used only there is never loaded from cache
    let cfg = Config::new();
    let mut defs = DefsIndex::new();
    defs.add_jar_var(Src::Clj, intern("lib.core"), intern("f"), VarInfo { flags: defs::F_FIXED, varargs_min: NO_ARITY, fixed: { let mut a = Arities::default(); a.add(1); a }, deprecated: Val::NONE });
    let mut fa = analyze_file("(ns a (:require [lib.core :as l]))\n(defn g [] (try (l/f 1) (catch Exception _ nil)))", FileKind::Clj, &cfg, &defs);
    defs.add_file(&fa);
    finish_usages(&mut fa, &defs);
    let u = usages(&fa, "f")[0];
    assert!(!u.has_fixed);
    assert_eq!(u.to, intern("lib.core"));
    // used outside try: info is loaded
    let mut fb = analyze_file("(ns b (:require [lib.core :as l]))\n(defn g [] (l/f 1))", FileKind::Clj, &cfg, &defs);
    defs.add_file(&fb);
    finish_usages(&mut fb, &defs);
    assert!(usages(&fb, "f")[0].has_fixed);
}

#[test]
fn cljc_is_analyzed_once_per_language_with_reader_conditionals_resolved() {
    let fa = run("(ns a)\n#?(:clj (defn f [x] x) :cljs (defn g [x] x))\n(defn both [] 1)", FileKind::Cljc);
    let names: Vec<(String, u8)> = fa.var_definitions.iter().map(|d| (d.name.as_str().to_owned(), d.lang)).collect();
    assert!(names.contains(&("f".into(), L_CLJ)));
    assert!(names.contains(&("g".into(), L_CLJS)));
    assert!(!names.contains(&("f".into(), L_CLJS)));
    assert_eq!(names.iter().filter(|n| n.0 == "both").count(), 2);
    assert_eq!(fa.namespace_definitions.len(), 2);
}

#[test]
fn hook_with_temp_dir_expands_to_let_without_from_var() {
    let mut cfg = Config::new();
    cfg.merge_edn("{:hooks {:analyze-call {babashka.fs/with-temp-dir babashka.fs/with-temp-dir}}}");
    let mut defs = DefsIndex::new();
    let mut fa = analyze_file("(ns a (:require [babashka.fs :as fs]))\n(defn f [] (fs/with-temp-dir [d {}] (str d)))", FileKind::Clj, &cfg, &defs);
    defs.add_file(&fa);
    finish_usages(&mut fa, &defs);
    let orig = usages(&fa, "with-temp-dir")[0];
    assert!(orig.from_var.is_none());
    let l = usages(&fa, "let")[0];
    assert!(l.derived && l.derived_name);
    assert!(fa.locals.iter().any(|l| l.name.as_str() == "d"));
}

/// `NX_FUZZ_DIR=<dir> cargo test --release -- --ignored fuzz_truncation`: analyzing truncated sources must not panic.
#[test]
#[ignore]
fn fuzz_truncation() {
    let Ok(dir) = std::env::var("NX_FUZZ_DIR") else { return };
    fn walk(d: &std::path::Path, o: &mut Vec<std::path::PathBuf>) {
        if let Ok(rd) = std::fs::read_dir(d) {
            for e in rd.flatten() {
                let p = e.path();
                if p.is_dir() {
                    walk(&p, o);
                } else if FileKind::from_path(&p.to_string_lossy()).map_or(false, |k| k != FileKind::Edn) {
                    o.push(p);
                }
            }
        }
    }
    let mut files = Vec::new();
    walk(std::path::Path::new(&dir), &mut files);
    let cfg = Config::new();
    let defs = DefsIndex::new();
    let mut n = 0;
    for p in files {
        let Ok(text) = std::fs::read_to_string(&p) else { continue };
        let kind = FileKind::from_path(&p.to_string_lossy()).unwrap();
        let len = text.len();
        for frac in [3usize, 7, 13, 29] {
            let mut cut = len * frac / 31;
            while !text.is_char_boundary(cut) {
                cut -= 1;
            }
            let t = &text[..cut];
            if std::env::var("NX_FUZZ_V").is_ok() {
                eprintln!("{} {}", p.display(), cut);
            }
            let r = std::panic::catch_unwind(|| {
                let fa = analyze_file(t, kind, &cfg, &defs);
                let _ = emit::to_json("x", "clj", &fa);
            });
            assert!(r.is_ok(), "panic on {} cut at {}", p.display(), cut);
            n += 1;
        }
        // delete a few bytes in the middle (deterministic)
        let mut seed = len as u64 * 2654435761 + 1;
        for _ in 0..4 {
            seed = seed.wrapping_mul(6364136223846793005).wrapping_add(1442695040888963407);
            let mut a = (seed >> 33) as usize % len.max(1);
            while !text.is_char_boundary(a) {
                a -= 1;
            }
            let mut b = (a + 1 + (seed >> 20) as usize % 12).min(len);
            while !text.is_char_boundary(b) {
                b += 1;
            }
            let t = format!("{}{}", &text[..a], &text[b..]);
            let r = std::panic::catch_unwind(|| {
                let fa = analyze_file(&t, kind, &cfg, &defs);
                let _ = emit::to_json("x", "clj", &fa);
            });
            assert!(r.is_ok(), "panic on {} deleting {}..{}", p.display(), a, b);
            n += 1;
        }
    }
    eprintln!("fuzzed {} inputs", n);
}
