/// Splits Clojure/EDN source into reader-token-ish chunks: runs of
/// characters NOT in the delimiter set `()[]{}"'~@^`,;#` and not
/// whitespace. Good enough to recover call-position symbols like `rand`,
/// `clojure.core/rand`, or `System/currentTimeMillis` as single tokens
/// without a real reader -- it is not a real reader (doesn't understand
/// string contents, `#_` discard, etc.), which is exactly why the
/// output-shape checks below exist as the primary defense and this is
/// secondary.
fn reader_tokens(src: &str) -> Vec<&str> {
    src.split(|c: char| c.is_whitespace() || "()[]{}\"'~@^`,;#".contains(c))
        .filter(|s| !s.is_empty())
        .collect()
}

/// Nondeterministic-source calls that are essentially never safe to print
/// directly or transitively into a golden. Excludes `rand`/`rand-int`/
/// `rand-nth`: real pending corpora already use these legitimately, masked
/// behind a coarse predicate (`(number? (rand))`, `(int? (rand-int 10))`)
/// -- see `is_masked_by_coarse_predicate` below. Wall-clock and identity
/// sources stay banned unconditionally: unlike a random number, there's no
/// common idiom that turns "the current time" or "a random UUID" into a
/// meaningfully different, reproducible check.
const UNCONDITIONALLY_BANNED_CALLS: &[&str] = &[
    "shuffle",
    "gensym",
    "System/currentTimeMillis",
    "System/nanoTime",
    "Math/random",
    "random-uuid",
    "java.util.UUID/randomUUID",
    "java.util.Date",
];

/// `rand`/`rand-int`/`rand-nth` ARE checked, but only outside this
/// allowlist of outer call positions -- functions coarse enough that
/// their result is the same regardless of which random value fed them.
/// If a pending form's outer form is one of these, the inner `rand*` call
/// is not flagged.
const COARSE_PREDICATE_ALLOWLIST: &[&str] = &[
    "number?", "int?", "float?", "double?", "string?", "symbol?", "keyword?", "coll?",
    "sequential?", "associative?", "set?", "map?", "vector?", "list?", "seq?", "boolean?",
    "nil?", "some?", "class", "type", "count",
];

const CONDITIONALLY_BANNED_CALLS: &[&str] = &["rand", "rand-int", "rand-nth"];

/// The symbol in call position of `src`, if `src`'s first non-whitespace
/// character opens a list -- i.e. `(number? ...)` -> `Some("number?")`.
/// Best-effort/textual, matching `reader_tokens`'s own limits.
fn outer_call_symbol(src: &str) -> Option<&str> {
    let trimmed = src.trim_start();
    if !trimmed.starts_with('(') {
        return None;
    }
    reader_tokens(trimmed).first().copied()
}

/// A gensym/auto-gensym-shaped token: Clojure's syntax-quote auto-gensym
/// (`foo__123__auto__`) and plain `(gensym)` (`G__123`) both end in
/// `__<digits>` optionally followed by `__auto__`. A false positive here
/// would require a HAND-WRITTEN identifier matching that exact shape,
/// which no pending corpus does today (grepped: zero hits).
fn looks_gensym_shaped(payload: &str) -> bool {
    let bytes = payload.as_bytes();
    let mut i = 0;
    while i + 1 < bytes.len() {
        if bytes[i] == b'_' && bytes[i + 1] == b'_' {
            let mut j = i + 2;
            let digit_start = j;
            while j < bytes.len() && bytes[j].is_ascii_digit() {
                j += 1;
            }
            if j > digit_start {
                return true;
            }
        }
        i += 1;
    }
    false
}

/// Best-effort check for an un-canonicalized multi-entry map/set literal
/// in a golden's `OK` payload: flat (non-nested) `{...}` groups with more
/// than one entry, where the entries' keys are not already in ascending
/// order. Per `CONFORMANCE-GUARANTEE.md`'s canonicalization rule 2, an
/// author who wants a deterministic multi-entry map/set golden is
/// expected to wrap it in `(into (sorted-map) ...)`/`(sorted-set ...)`;
/// if the corpus form's OWN source text already mentions `sorted-map` or
/// `sorted-set`, this check is skipped entirely (the author already
/// canonicalized; sorted collections print in their own sort order, which
/// this same ascending check would otherwise correctly pass anyway, but
/// skipping avoids re-deriving that from print order alone).
///
/// Deliberately conservative in one direction: many small (<=8 entry)
/// literal maps/sets ARE printed in stable insertion order by real
/// Clojure's array-map/array-set representation, so an unsorted-looking
/// literal here is not proof of true nondeterminism -- it is a proxy for
/// "the author didn't canonicalize", which is the actionable finding
/// either way (wrap it, and the golden becomes robust to a future
/// representation change too).
fn has_unsorted_multi_entry_literal(payload: &str) -> Option<String> {
    let bytes = payload.as_bytes();
    let mut i = 0;
    while i < bytes.len() {
        if bytes[i] == b'{' {
            if let Some(close_rel) = payload[i + 1..].find(['{', '}']) {
                let close = i + 1 + close_rel;
                if bytes[close] == b'}' {
                    let inner = &payload[i + 1..close];
                    if let Some(reason) = unsorted_entries(inner) {
                        return Some(reason);
                    }
                }
            }
        }
        i += 1;
    }
    None
}

fn unsorted_entries(inner: &str) -> Option<String> {
    let entries: Vec<&str> = inner.split(", ").map(str::trim).filter(|s| !s.is_empty()).collect();
    if entries.len() < 2 {
        return None;
    }
    let keys: Vec<&str> = entries.iter().map(|e| e.split(' ').next().unwrap_or(e)).collect();
    if keys.windows(2).any(|w| w[0] > w[1]) {
        Some(format!("multi-entry {{...}} literal not in ascending key order: {inner:?}"))
    } else {
        None
    }
}

/// Runs every canonicalization check against one pending form. Returns
/// `Some(reason)` if the form should be rejected outright -- see the
/// module doc's "Canonicalization lint" section for the policy this
/// implements, and this function's own sub-checks for exactly what each
/// one catches. What it CANNOT catch, by construction: nondeterminism
/// hidden behind a coarse predicate this allowlist doesn't happen to
/// include, nondeterminism inside a NESTED map/set literal (the
/// unsorted-literal check only looks at flat, non-nested `{...}` spans),
/// and any nondeterministic value that happens to print identically on
/// every run by coincidence (e.g. a `rand` draw that always lands on the
/// same float would never be caught by any static check -- only running
/// the golden generator twice and diffing would, which is
/// `tools/gen-pending.sh`'s job, not this in-process lint's).
fn lint_nondeterminism(src: &str, golden: &Golden) -> Option<String> {
    let tokens = reader_tokens(src);
    for banned in UNCONDITIONALLY_BANNED_CALLS {
        if tokens.iter().any(|t| *t == *banned || t.rsplit('/').next() == Some(banned)) {
            return Some(format!(
                "form calls `{banned}`, a nondeterministic/wall-clock source with no safe masked usage"
            ));
        }
    }
    let masked = outer_call_symbol(src).map(|s| COARSE_PREDICATE_ALLOWLIST.contains(&s)).unwrap_or(false);
    if !masked {
        for banned in CONDITIONALLY_BANNED_CALLS {
            if tokens.iter().any(|t| *t == *banned || t.rsplit('/').next() == Some(banned)) {
                return Some(format!(
                    "form calls `{banned}` without wrapping it in a coarse predicate ({}); \
                     its printed value is not reproducible across golden regenerations",
                    COARSE_PREDICATE_ALLOWLIST.join("/")
                ));
            }
        }
    }
    if let Golden::Ok(payload) = golden {
        if payload.contains("#object[") {
            return Some(
                "golden payload contains `#object[` -- JVM object identity/hashcode is not stable across runs"
                    .to_string(),
            );
        }
        if looks_gensym_shaped(payload) {
            return Some(
                "golden payload contains a gensym-shaped token (`__<digits>`) -- gensym names are not stable across runs"
                    .to_string(),
            );
        }
        if !src.contains("sorted-map") && !src.contains("sorted-set") {
            if let Some(reason) = has_unsorted_multi_entry_literal(payload) {
                return Some(format!(
                    "{reason} -- wrap in `(into (sorted-map) ...)`/`(into (sorted-set) ...)` for a canonical golden"
                ));
            }
        }
    }
    None
}

