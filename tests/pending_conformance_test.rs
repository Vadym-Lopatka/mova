#[test]
#[ignore = "known failure: 50 pending forms now match real Clojure, the ledger is stale"]
fn pending_conformance_ledger() {
    let binary = env!("CARGO_BIN_EXE_mova");
    let files = pending_areas();
    assert!(!files.is_empty(), "no *.corpus files found under tests/conformance/pending");

    let mut rejected: Vec<String> = Vec::new();
    let mut promotable: Vec<String> = Vec::new();
    let mut grand_total = 0usize;
    let mut grand_diverge = 0usize;
    let mut grand_err_both = 0usize;
    let mut grand_timeout = 0usize;
    let mut grand_unreached = 0usize;

    for corpus_path in &files {
        let area = corpus_path.file_stem().unwrap().to_string_lossy().into_owned();
        let golden_path = corpus_path.with_extension("golden");
        let forms = parse_corpus(corpus_path);
        let golden = parse_golden(&golden_path);
        assert_eq!(
            forms.len(),
            golden.len(),
            "{area}.corpus has {} form(s) but {area}.golden has {} line(s) -- \
             re-run `tools/gen-pending.sh {area}` to regenerate",
            forms.len(),
            golden.len()
        );

        // ONE session for the whole file (see module doc's "Session
        // model"), not one process per form -- a `def` on an earlier
        // line must be visible to a later line, matching the golden
        // side's own session model.
        let outcomes = run_session(binary, &forms, &area);
        assert_eq!(outcomes.len(), forms.len(), "{area}: outcome count didn't match form count");

        let mut diverge = 0usize;
        let mut err_both = 0usize;
        let mut timeout = 0usize;
        let mut unreached = 0usize;

        for ((form, expected), outcome) in forms.iter().zip(golden.iter()).zip(outcomes.iter()) {
            grand_total += 1;

            if let Some(reason) = lint_nondeterminism(&form.src, expected) {
                rejected.push(format!(
                    "{area}.corpus:{}: {}\n    REJECTED (canonicalization lint): {reason}",
                    form.line, form.src
                ));
                continue;
            }

            match classify(expected, outcome) {
                Classification::Conform => {
                    let Golden::Ok(v) = expected else { unreachable!() };
                    promotable.push(format!(
                        "{area}.corpus:{}: {}\n    both sides agree: OK\t{v}\n    \
                         ACTION: promote this form (with its golden) to tests/conformance/corpus/, \
                         then delete it from {area}.corpus/{area}.golden/{area}.mova",
                        form.line, form.src
                    ));
                }
                Classification::ErrBoth => err_both += 1,
                Classification::Diverge => diverge += 1,
                // TIMEOUT and UNREACHED are both EXCLUSIVE of DIVERGE
                // (see module doc) -- this must match
                // tools/generate-compat-report.bb's `pending-ledger-section`
                // bucket math exactly, since that script derives the same
                // classification independently from the committed
                // `.golden`/`.mova` columns and the two totals are meant
                // to be cross-checked against each other.
                Classification::Timeout => timeout += 1,
                // Unreached carries no evidence either way: not debt
                // (Diverge/ErrBoth), not agreement (Conform). Counted
                // only in its own bucket.
                Classification::Unreached => unreached += 1,
            }
        }

        println!(
            "pending[{area:<20}] {:>4} forms | {:>4} DIVERGE | {:>4} ERR-BOTH (needs error taxonomy) | \
             {:>3} TIMEOUT | {:>3} UNREACHED",
            forms.len(),
            diverge,
            err_both,
            timeout,
            unreached
        );

        grand_diverge += diverge;
        grand_err_both += err_both;
        grand_timeout += timeout;
        grand_unreached += unreached;
    }

    println!(
        "pending TOTAL: {grand_total} forms across {} area(s) | {grand_diverge} DIVERGE | \
         {grand_err_both} ERR-BOTH | {grand_timeout} TIMEOUT | {grand_unreached} UNREACHED",
        files.len()
    );

    if !rejected.is_empty() || !promotable.is_empty() {
        let mut msg = String::new();
        if !promotable.is_empty() {
            msg.push_str(&format!(
                "{} pending form(s) now CONFORM with real Clojure -- they are no longer pending:\n\n",
                promotable.len()
            ));
            msg.push_str(&promotable.join("\n\n"));
            msg.push('\n');
        }
        if !rejected.is_empty() {
            if !msg.is_empty() {
                msg.push('\n');
            }
            msg.push_str(&format!(
                "{} pending form(s) rejected by the canonicalization lint (see tests/conformance/pending/README.md):\n\n",
                rejected.len()
            ));
            msg.push_str(&rejected.join("\n\n"));
            msg.push('\n');
        }
        panic!("{msg}");
    }
}
